/* ------------------------------------------------------------------ API */
function t(lang, key, params) {
  const d = D[lang] || D.en;
  let s = d[key] !== undefined ? d[key] : (D.en[key] !== undefined ? D.en[key] : key);
  if (typeof s === 'string' && params) s = s.replace(/\{(\w+)\}/g, (_m, k) => (k in params ? params[k] : ''));
  return s;
}

/* Elige el idioma a partir del idioma del sistema (p. ej. "es-ES", "zh-CN", "pt-BR") */
function detect(locale) {
  const code = String(locale || '').toLowerCase().split(/[-_]/)[0];
  return LANGS[code] ? code : 'en';
}

/* Diccionario completo con respaldo en inglés (se envía a la interfaz) */
function strings(lang) { return Object.assign({}, D.en, D[lang] || {}); }

const list = () => Object.entries(LANGS).map(([c, m]) => `${c} (${m.name})`).join(', ');

/* Permite añadir o sobrescribir claves de un idioma (lo usa la versión web) */
function extend(lang, obj) { D[lang] = Object.assign(D[lang] || {}, obj); }

const api = { LANGS, t, detect, strings, list, extend };
if (typeof module !== 'undefined' && module.exports) module.exports = api;
else if (typeof window !== 'undefined') window.CapriI18n = api;
